sidebar_link <- function(value, icon_name, label, badge = NULL, active = FALSE) {
  tags$a(
    href = "#",
    class = paste("sidebar-link", if (active) "active" else ""),
    `data-tab` = value,
    `aria-current` = if (active) "page" else NULL,
    tags$span(class = "sidebar-icon", icon(icon_name)),
    tags$span(class = "sidebar-label", label),
    if (!is.null(badge)) tags$span(class = "sidebar-badge", badge)
  )
}

# Card header with a step number, used by the CliPP-on-Web flow
# ---- Tutorial building blocks --------------------------------------------
# Figures live in assets/img/tutorial/ and are regenerated by
# tools/tutorial/capture.R + annotate.R. The numbered markers burned into each
# image line up with tut_points() beside it, so rewording a step never needs a
# re-render.

tut_figure <- function(file, alt) {
  div(class = "tut-figure",
    tags$img(src = file.path(global_assets, "img", "tutorial", file),
             alt = alt, loading = "lazy")
  )
}

tut_points <- function(...) {
  tags$ol(class = "tut-points", lapply(list(...), tags$li))
}

tut_section <- function(id, number, title, meta = NULL, ...) {
  div(id = id, class = "about-card tut-card",
    step_header(number, title, meta),
    div(class = "about-card-body", ...)
  )
}

step_header <- function(number, title, meta = NULL) {
  div(class = "about-card-header",
    div(class = "step-heading",
      div(class = "step-number", number),
      h4(class = "about-card-title", title)
    ),
    if (!is.null(meta)) span(class = "about-card-meta", meta)
  )
}

